#!/usr/bin/env node
/**
 * Generates the blind worksheet used to set metric 1's ground truth by hand.
 *
 * Blind on purpose: it emits the two startup documents and the rubric ladders
 * and nothing else. The seeded levels, any derived reference, and every arm's
 * output are deliberately absent, because the reference has to be set without
 * knowing which way it moves the result.
 *
 * Rubric text is read from the corpus rather than retyped, so the worksheet
 * cannot drift from what the model is actually shown.
 */

const fs = require('fs');
const path = require('path');

const DIMENSIONS = ['Technology', 'Market', 'Acceptance', 'Organizational', 'Regulatory', 'Investment'];
const ABBREV = { Technology: 'TRL', Market: 'MRL', Acceptance: 'ARL', Organizational: 'ORL', Regulatory: 'RRL', Investment: 'IRL' };

// Full text to 7; titles only above, where both documents are implausible. Say
// so rather than truncating silently — 8 and 9 stay reachable on request.
const FULL_TEXT_THROUGH = 7;

const OUT = path.join(__dirname, 'data', 'ground-truth-adjudication.md');

function documents() {
  const src = fs.readFileSync(path.join(__dirname, 'measure-grounding.js'), 'utf8');
  const out = {};
  for (const name of ['AgroLink PH', 'MediSync Cebu']) {
    const m = src.match(new RegExp(`'${name}':\\s*\\{\\s*\\n\\s*doc: \`([\\s\\S]*?)\`,`));
    if (!m) throw new Error(`could not extract document for ${name}`);
    out[name] = m[1];
  }
  return out;
}

function main() {
  const rubrics = require(path.join(__dirname, '..', 'data', 'rag-corpus', 'readiness-rubrics.json'));
  const docs = documents();
  const L = [];

  L.push('# Ground-truth adjudication worksheet');
  L.push('');
  L.push('Generated by `measurement/build-adjudication-worksheet.js`. Regenerate rather than hand-edit above the answer tables.');
  L.push('');
  L.push('## What this is for');
  L.push('');
  L.push("Metric 1 of the grounding study scores the model's readiness-level placement against a reference. The reference in use was copied from the demo seeder, which was written for the UI and never checked against these documents. Several of its levels are contradicted by the document text, so the study needs a reference set deliberately.");
  L.push('');
  L.push('**This worksheet is blind on purpose.** It does not show the seeded levels, any reference I derived, or what any model arm answered. Setting the reference without seeing those is what makes the resulting numbers quotable — if you want them first, say so, but then the reference is anchored and the result is weaker.');
  L.push('');
  L.push('## The rule');
  L.push('');
  L.push('For each dimension, pick **the highest level whose core condition the document supports.** Two readings are worth separating where they differ:');
  L.push('');
  L.push('- **strict** — the condition is stated outright in the document.');
  L.push('- **permissive** — the condition is entailed by something stated, though not named.');
  L.push('');
  L.push('Fill both columns. Put the same number in both where the distinction does not bite. Add the document phrase you read it from — that is what makes the cell checkable later.');
  L.push('');
  L.push(`Rubric text below is verbatim from the corpus the model is shown. Levels 1-${FULL_TEXT_THROUGH} carry full text; 8 and 9 are titles only, because both documents are early/mid stage. Ask for the full text if you want to place anything that high.`);
  L.push('');
  L.push('---');
  L.push('');
  L.push('## The rubric ladders');

  for (const dim of DIMENSIONS) {
    L.push('');
    L.push(`### ${dim} (${ABBREV[dim]})`);
    L.push('');
    for (const row of rubrics.filter((r) => r.readinessType === dim).sort((a, b) => a.level - b.level)) {
      if (row.level <= FULL_TEXT_THROUGH) {
        L.push(`**${row.title}**`);
        L.push('');
        L.push(row.content);
        L.push('');
      } else {
        L.push(`**${row.title}** *(title only — ask for full text)*`);
        L.push('');
      }
    }
  }

  L.push('---');
  L.push('');
  L.push('## The documents');
  L.push('');
  L.push('These are exactly what the model is given — no more, no less.');

  for (const [name, doc] of Object.entries(docs)) {
    L.push('');
    L.push(`### ${name}`);
    L.push('');
    L.push('```');
    L.push(doc);
    L.push('```');
    L.push('');
    L.push('| dimension | strict | permissive | document phrase you read it from |');
    L.push('|---|---|---|---|');
    for (const dim of DIMENSIONS) L.push(`| ${dim} (${ABBREV[dim]}) | | | |`);
  }

  L.push('');
  L.push('---');
  L.push('');
  L.push('## When done');
  L.push('');
  L.push('Tell me and I will fold these into `audit-ground-truth.js`, re-score the collected runs against them, and rewrite the write-ups to whatever the numbers then say — including leaving the negative conclusion standing if that is where it lands.');
  L.push('');

  fs.writeFileSync(OUT, L.join('\n'), 'utf8');
  console.log(`wrote ${OUT}`);
}

if (require.main === module) main();
