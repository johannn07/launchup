#!/usr/bin/env node
/**
 * Generates the worksheet used to set metric 1's ground truth.
 *
 * Default output is blind: the two startup documents and the rubric ladders and
 * nothing else. The seeded levels, any derived reference, and every arm's output
 * are deliberately absent, because a reference set knowing which way it moves
 * the result is not worth much.
 *
 * `--filled` instead emits the current model-adjudicated reference, read from
 * audit-ground-truth.js so the worksheet cannot disagree with the scorer, and
 * banners it as model-set. That banner is the point: a filled worksheet sitting
 * in the repo must never be mistakable for an independent human pass.
 *
 * Rubric text and documents come from the corpus and the harness rather than
 * being retyped, so neither can drift from what the model is shown.
 */

const fs = require('fs');
const path = require('path');

const { loadDocuments, DERIVED, DIMENSIONS } = require('./audit-ground-truth');

const ABBREV = { Technology: 'TRL', Market: 'MRL', Acceptance: 'ARL', Organizational: 'ORL', Regulatory: 'RRL', Investment: 'IRL' };

// Full text to 7; titles only above, where both documents are implausible. Say
// so rather than truncating silently — 8 and 9 stay reachable on request.
const FULL_TEXT_THROUGH = 7;

const OUT = path.join(__dirname, 'data', 'ground-truth-adjudication.md');

function render(filled) {
  const rubrics = require(path.join(__dirname, '..', 'data', 'rag-corpus', 'readiness-rubrics.json'));
  const docs = loadDocuments();
  const L = [];

  L.push('# Ground-truth adjudication worksheet');
  L.push('');
  if (filled) {
    L.push('> ## ⚠ Model-adjudicated, not human-set');
    L.push('>');
    L.push('> The levels below were set by **Claude**, from the documents and rubric ladders in this file. They are the same cells as `DERIVED` in `measurement/audit-ground-truth.js` — generated from it, so the two cannot disagree.');
    L.push('>');
    L.push('> **This cannot establish that a corpus arm places better.** An adjudicator reading the document with the full rubric ladder in front of it is approximately the `deviation-deterministic` condition, so its agreement with that arm is close to circular. It was also set after the run results were known.');
    L.push('>');
    L.push('> What it *is* good for: retiring the seeded reference, which rests on the seeded levels being contradicted by their own documents, and holds however these cells are set. For any claim about which arm is better, use the reference-free `HARD_ABSENCES` check instead.');
    L.push('>');
    L.push('> A human pass would break the circularity. `node measurement/build-adjudication-worksheet.js` (no flag) regenerates this file blank for exactly that.');
    L.push('');
  }
  L.push('Generated by `measurement/build-adjudication-worksheet.js`' + (filled ? ' `--filled`' : '') + '. Regenerate rather than hand-edit.');
  L.push('');
  L.push('## What this is for');
  L.push('');
  L.push("Metric 1 of the grounding study scores the model's readiness-level placement against a reference. The reference in use was copied from the demo seeder, which was written for the UI and never checked against these documents. Several of its levels are contradicted by the document text, so the study needs a reference set deliberately.");
  L.push('');
  if (filled) {
    L.push('The blank form of this worksheet shows no seeded levels, no derived reference and no arm output, so a reader can set the cells unanchored. This filled form necessarily gives that up.');
  } else {
    L.push('**This worksheet is blind on purpose.** It does not show the seeded levels, any reference I derived, or what any model arm answered. Setting the reference without seeing those is what makes the resulting numbers quotable — if you want them first, say so, but then the reference is anchored and the result is weaker.');
  }
  L.push('');
  L.push('## The rule');
  L.push('');
  L.push('For each dimension, pick **the highest level whose core condition the document supports.** Two readings are worth separating where they differ:');
  L.push('');
  L.push('- **strict** — the condition is stated outright in the document.');
  L.push('- **permissive** — the condition is entailed by something stated, though not named.');
  L.push('');
  L.push(filled
    ? 'Both columns are filled. Where they carry the same number, the distinction did not bite. The fourth column is the document phrase the level was read from, so every cell is checkable against the document without re-reading the rubric.'
    : 'Fill both columns. Put the same number in both where the distinction does not bite. Add the document phrase you read it from — that is what makes the cell checkable later.');
  L.push('');
  L.push(`Rubric text below is verbatim from the corpus the model is shown. Levels 1-${FULL_TEXT_THROUGH} carry full text; 8 and 9 are titles only, because both documents are early/mid stage. Ask for the full text if you want to place anything that high.`);
  L.push('');
  L.push('---');
  L.push('');
  L.push('## The rubric ladders');

  for (const dim of DIMENSIONS) {
    L.push('');
    L.push(`### ${dim} (${ABBREV[dim]})`);
    L.push('');
    for (const row of rubrics.filter((r) => r.readinessType === dim).sort((a, b) => a.level - b.level)) {
      if (row.level <= FULL_TEXT_THROUGH) {
        L.push(`**${row.title}**`);
        L.push('');
        L.push(row.content);
        L.push('');
      } else {
        L.push(`**${row.title}** *(title only — ask for full text)*`);
        L.push('');
      }
    }
  }

  L.push('---');
  L.push('');
  L.push('## The documents');
  L.push('');
  L.push('These are exactly what the model is given — no more, no less.');

  for (const [name, doc] of Object.entries(docs)) {
    L.push('');
    L.push(`### ${name}`);
    L.push('');
    L.push('```');
    L.push(doc);
    L.push('```');
    L.push('');
    L.push(`| dimension | strict | permissive | document phrase ${filled ? 'it was' : 'you read it'} from |`);
    L.push('|---|---|---|---|');
    for (const dim of DIMENSIONS) {
      if (!filled) {
        L.push(`| ${dim} (${ABBREV[dim]}) | | | |`);
        continue;
      }
      const cell = DERIVED[name][dim];
      L.push(`| ${dim} (${ABBREV[dim]}) | **${cell.strict}** | **${cell.permissive}** | "${cell.quote}" |`);
    }
    if (filled) {
      L.push('');
      L.push('<details><summary>Why each level, and what rules out the one above</summary>');
      L.push('');
      for (const dim of DIMENSIONS) L.push(`- **${dim}** — ${DERIVED[name][dim].why}`);
      L.push('');
      L.push('</details>');
    }
  }

  L.push('');
  L.push('---');
  L.push('');
  if (filled) {
    L.push('## Where these are already used');
    L.push('');
    L.push('`node measurement/audit-ground-truth.js` scores the collected runs against these as the `strict` and `permissive` references, alongside the seeded one, and prints the reference-free check underneath. Nothing further is pending on this file.');
    L.push('');
    L.push('To replace these with a human reference: regenerate blank, fill it in, and hand it back — the cells map one-to-one onto `DERIVED`.');
  } else {
    L.push('## When done');
    L.push('');
    L.push('Tell me and I will fold these into `audit-ground-truth.js`, re-score the collected runs against them, and rewrite the write-ups to whatever the numbers then say — including leaving the negative conclusion standing if that is where it lands.');
  }
  L.push('');

  return L.join('\n');
}

function main() {
  const filled = process.argv.includes('--filled');
  fs.writeFileSync(OUT, render(filled), 'utf8');
  console.log(`wrote ${OUT}${filled ? ' (filled, model-adjudicated)' : ' (blind)'}`);
}

if (require.main === module) main();

module.exports = { render, OUT };
